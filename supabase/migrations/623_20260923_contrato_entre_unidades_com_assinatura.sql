  FOR DELETE TO authenticated
  USING (
    bucket_id = 'contratos'
    AND (owner = (SELECT auth.uid()) OR (SELECT auth_user_role()) = 'admin')
    AND NOT EXISTS (
      SELECT 1 FROM public.contratos c
       WHERE c.arquivo_path = storage.objects.name AND c.status <> 'rascunho'
    )
  );

