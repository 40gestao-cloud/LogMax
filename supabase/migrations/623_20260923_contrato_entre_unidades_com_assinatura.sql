-- 2. RLS de `contratos`
-- ────────────────────────────────────────────────────────────────────────────

DROP POLICY IF EXISTS contratos_select ON public.contratos;
CREATE POLICY contratos_select ON public.contratos
  FOR SELECT TO authenticated
  USING (
    (SELECT auth_user_role()) = 'admin'
    OR ((SELECT auth_user_role()) IN ('ceo', 'conselheiro') AND status <> 'rascunho')
    OR ((SELECT auth_user_role()) = 'gerente' AND (
          (SELECT auth_user_filial()) = parte_a
          OR ((SELECT auth_user_filial()) = parte_b AND status <> 'rascunho')))
  );

-- Cria quem representa a parte A, sempre como rascunho e em nome próprio.
DROP POLICY IF EXISTS contratos_insert ON public.contratos;
CREATE POLICY contratos_insert ON public.contratos
  FOR INSERT TO authenticated
  WITH CHECK (
    status = 'rascunho'
    AND criado_por = (SELECT auth.uid())
    AND (
      ((SELECT auth_user_role()) = 'admin' AND parte_a = 'Matriz')
      OR ((SELECT auth_user_role()) = 'gerente' AND parte_a <> 'Matriz'
          AND (SELECT auth_user_filial()) = parte_a)
    )
  );

-- Editar: só rascunho, só a parte A. O WITH CHECK repete o status, senão o
-- UPDATE escreveria 'vigente' por fora da RPC.
DROP POLICY IF EXISTS contratos_update ON public.contratos;
CREATE POLICY contratos_update ON public.contratos
  FOR UPDATE TO authenticated
  USING (
    status = 'rascunho'
    AND (
      ((SELECT auth_user_role()) = 'admin' AND parte_a = 'Matriz')
      OR ((SELECT auth_user_role()) = 'gerente' AND parte_a <> 'Matriz'
          AND (SELECT auth_user_filial()) = parte_a)
    )
  )
  WITH CHECK (
    status = 'rascunho'
    AND (
      ((SELECT auth_user_role()) = 'admin' AND parte_a = 'Matriz')
      OR ((SELECT auth_user_role()) = 'gerente' AND parte_a <> 'Matriz'
          AND (SELECT auth_user_filial()) = parte_a)
    )
  );

-- Excluir: a parte A o próprio rascunho; o professor qualquer um (limpeza de
-- turma). Contrato assinado não some pela mão do aluno.
DROP POLICY IF EXISTS contratos_delete ON public.contratos;
CREATE POLICY contratos_delete ON public.contratos
  FOR DELETE TO authenticated
  USING (
    (SELECT auth_user_role()) = 'admin'
    OR (status = 'rascunho'
        AND (SELECT auth_user_role()) = 'gerente' AND parte_a <> 'Matriz'
        AND (SELECT auth_user_filial()) = parte_a)
  );

-- Assinaturas: vê quem vê o contrato. A subconsulta passa pela RLS de
-- `contratos`, então a régua é uma só.
DROP POLICY IF EXISTS contratos_assinaturas_select ON public.contratos_assinaturas;
CREATE POLICY contratos_assinaturas_select ON public.contratos_assinaturas
  FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.contratos c WHERE c.id = contrato_id));

-- ────────────────────────────────────────────────────────────────────────────
-- 3. Quem representa a parte — para as RPCs (policy escreve inline)
-- ────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.contrato_representa(p_parte text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
  SELECT COALESCE((
    SELECT (p.role = 'admin' AND p_parte = 'Matriz')
        OR (p.role = 'gerente' AND p_parte <> 'Matriz' AND p.filial = p_parte)
      FROM public.user_profiles p
     WHERE p.id = auth.uid() AND p.desligado_em IS NULL
  ), false);
$function$;

COMMENT ON FUNCTION public.contrato_representa(text) IS
  'Migr. 623 — quem está logado assina por esta parte? Matriz = role admin literal; filial = o gerente dela. As policies de contratos repetem a régua inline (padrão 597/598).';

REVOKE ALL ON FUNCTION public.contrato_representa(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.contrato_representa(text) TO authenticated, service_role;

-- ────────────────────────────────────────────────────────────────────────────
-- 4. Assinar
-- ────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.assinar_contrato(p_contrato_id uuid, p_sha256 text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_c      public.contratos;
  v_parte  text;
  v_nome   text;
  v_role   text;
  v_total  int;
  v_status text;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Não autenticado.' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO v_c FROM public.contratos WHERE id = p_contrato_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Contrato não encontrado.' USING ERRCODE = 'P0002';
  END IF;

  IF public.contrato_representa(v_c.parte_a) THEN
    v_parte := v_c.parte_a;
  ELSIF public.contrato_representa(v_c.parte_b) AND v_c.status <> 'rascunho' THEN
    v_parte := v_c.parte_b;
  ELSE
    RAISE EXCEPTION 'Só o gerente de uma das partes (ou o professor, pela Matriz) assina este contrato.'
      USING ERRCODE = '42501';
  END IF;

  IF v_c.status NOT IN ('rascunho', 'aguardando') THEN
    RAISE EXCEPTION 'Este contrato está % e não recebe mais assinatura.', v_c.status
      USING ERRCODE = 'P0001';
  END IF;

  IF v_c.vigencia_fim IS NOT NULL
     AND v_c.vigencia_fim < (now() AT TIME ZONE 'America/Rio_Branco')::date THEN
    RAISE EXCEPTION 'A vigência deste contrato já terminou (%). Não se assina contrato vencido.',
      to_char(v_c.vigencia_fim, 'DD/MM/YYYY') USING ERRCODE = 'P0001';
  END IF;

  -- O resumo que quem assina conferiu tem de ser o do arquivo guardado. Se não
  -- bate, a pessoa está assinando outra coisa que não o contrato.
  IF lower(COALESCE(p_sha256, '')) <> v_c.arquivo_sha256 THEN
    RAISE EXCEPTION 'O arquivo conferido não é o do contrato (resumo SHA-256 diferente). Recarregue a tela e confira de novo.'
      USING ERRCODE = 'P0001';
  END IF;

  IF EXISTS (SELECT 1 FROM public.contratos_assinaturas
              WHERE contrato_id = v_c.id AND parte = v_parte) THEN
    RAISE EXCEPTION 'A % já assinou este contrato.', v_parte USING ERRCODE = 'P0001';
  END IF;

  SELECT nome, role INTO v_nome, v_role FROM public.user_profiles WHERE id = auth.uid();

  INSERT INTO public.contratos_assinaturas
    (contrato_id, parte, user_id, nome_snapshot, cargo_snapshot, arquivo_sha256)
  VALUES
    (v_c.id, v_parte, auth.uid(), COALESCE(v_nome, '—'),
     CASE v_role WHEN 'admin' THEN 'Administrador (Matriz)' ELSE 'Gerente' END,
     v_c.arquivo_sha256);

  SELECT count(*) INTO v_total FROM public.contratos_assinaturas WHERE contrato_id = v_c.id;

  IF v_total >= 2 THEN
    v_status := 'vigente';
    UPDATE public.contratos
       SET status = 'vigente', vigente_desde = now(), enviado_em = COALESCE(enviado_em, now())
     WHERE id = v_c.id;
  ELSE
    v_status := 'aguardando';
    UPDATE public.contratos
       SET status = 'aguardando', enviado_em = COALESCE(enviado_em, now())
     WHERE id = v_c.id;
  END IF;

  RETURN v_status;
END;
$function$;

REVOKE ALL ON FUNCTION public.assinar_contrato(uuid, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.assinar_contrato(uuid, text) TO authenticated, service_role;

-- ────────────────────────────────────────────────────────────────────────────
-- 5. Recusar (parte B) ou retirar (parte A) — só enquanto aguarda
-- ────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.recusar_contrato(p_contrato_id uuid, p_motivo text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_c    public.contratos;
  v_nome text;
BEGIN
  SELECT * INTO v_c FROM public.contratos WHERE id = p_contrato_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Contrato não encontrado.' USING ERRCODE = 'P0002';
  END IF;

  IF NOT (public.contrato_representa(v_c.parte_a) OR public.contrato_representa(v_c.parte_b)) THEN
    RAISE EXCEPTION 'Só quem representa uma das partes recusa o contrato.' USING ERRCODE = '42501';
  END IF;

  IF v_c.status <> 'aguardando' THEN
    RAISE EXCEPTION 'Só se recusa contrato que está aguardando assinatura.' USING ERRCODE = 'P0001';
  END IF;

  IF length(btrim(COALESCE(p_motivo, ''))) < 5 THEN
    RAISE EXCEPTION 'Diga o motivo da recusa — é o que a outra parte vai ler.' USING ERRCODE = 'P0001';
  END IF;

  SELECT nome INTO v_nome FROM public.user_profiles WHERE id = auth.uid();

  UPDATE public.contratos
     SET status = 'recusado', encerrado_em = now(),
         encerrado_por_nome = v_nome, motivo_encerramento = btrim(p_motivo)
   WHERE id = v_c.id;
END;
$function$;

REVOKE ALL ON FUNCTION public.recusar_contrato(uuid, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.recusar_contrato(uuid, text) TO authenticated, service_role;

-- ────────────────────────────────────────────────────────────────────────────
-- 6. Encerrar (fim combinado) ou rescindir (rompimento) — só vigente
-- ────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.encerrar_contrato(p_contrato_id uuid, p_rescisao boolean, p_motivo text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_c    public.contratos;
  v_nome text;
BEGIN
  SELECT * INTO v_c FROM public.contratos WHERE id = p_contrato_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Contrato não encontrado.' USING ERRCODE = 'P0002';
  END IF;

  IF NOT (public.contrato_representa(v_c.parte_a) OR public.contrato_representa(v_c.parte_b)) THEN
    RAISE EXCEPTION 'Só quem representa uma das partes encerra o contrato.' USING ERRCODE = '42501';
  END IF;

  IF v_c.status <> 'vigente' THEN
    RAISE EXCEPTION 'Só se encerra contrato vigente.' USING ERRCODE = 'P0001';
  END IF;

  IF COALESCE(p_rescisao, false) AND length(btrim(COALESCE(p_motivo, ''))) < 5 THEN
    RAISE EXCEPTION 'Rescisão pede motivo.' USING ERRCODE = 'P0001';
  END IF;

  SELECT nome INTO v_nome FROM public.user_profiles WHERE id = auth.uid();

  UPDATE public.contratos
     SET status = CASE WHEN COALESCE(p_rescisao, false) THEN 'rescindido' ELSE 'encerrado' END,
         encerrado_em = now(), encerrado_por_nome = v_nome,
         motivo_encerramento = NULLIF(btrim(COALESCE(p_motivo, '')), '')
   WHERE id = v_c.id;
END;
$function$;

REVOKE ALL ON FUNCTION public.encerrar_contrato(uuid, boolean, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.encerrar_contrato(uuid, boolean, text) TO authenticated, service_role;

