DO $$
DECLARE
  t      text;
  v_cmd  text;
  v_nome text;
BEGIN
  FOREACH t IN ARRAY ARRAY['contratos', 'contratos_assinaturas'] LOOP
    FOREACH v_cmd IN ARRAY ARRAY['INSERT', 'UPDATE', 'DELETE'] LOOP
      v_nome := 'zz_desligado_bloqueia_' || lower(v_cmd);
      EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', v_nome, t);
      IF v_cmd = 'INSERT' THEN
        EXECUTE format(
          'CREATE POLICY %I ON public.%I AS RESTRICTIVE FOR INSERT TO authenticated
             WITH CHECK (NOT (SELECT auth_desligado()))', v_nome, t);
      ELSE
        EXECUTE format(
          'CREATE POLICY %I ON public.%I AS RESTRICTIVE FOR %s TO authenticated
             USING (NOT (SELECT auth_desligado()))', v_nome, t, v_cmd);
      END IF;
    END LOOP;
  END LOOP;
END $$;

