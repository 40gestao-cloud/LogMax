-- 623 — Contratos entre unidades, com assinatura eletrônica simples.
--
-- As filiais fazem negócio com a Matriz e entre si (serviço prestado, cessão
-- de espaço, fornecimento, mútuo), e o acordo não existia no sistema: o valor
-- aparecia no financeiro sem o papel que o justifica. Documentos (476/528) não
-- serve, porque lá quem publica fala e quem recebe lê. Contrato é acordo entre
-- DUAS PARTES, e cada uma precisa aceitar.
--
-- ─── QUEM REPRESENTA CADA PARTE ─────────────────────────────────────────────
--
-- Parte é uma unidade: 'Matriz', 'SuperMax', 'MaxLook' ou 'TechMax'.
--   • Filial: o GERENTE dela. Ele cria, envia, assina, recusa, encerra.
--   • Matriz: o ADMIN (o professor), `role = 'admin'` LITERAL. A Matriz não
--     tem gerente, e `auth_is_admin()` incluiria CEO e conselheiro, que são
--     alunos (vide feedback_auth_is_admin_inclui_alunos).
-- CEO e conselheiro LEEM todos os contratos (menos rascunho alheio); não
-- assinam. Colaborador não vê contrato nenhum: é papel de gestão.
--
-- ─── O CICLO ────────────────────────────────────────────────────────────────
--
--   rascunho ──(A assina)──▶ aguardando ──(B assina)──▶ vigente ──▶ encerrado
--                                │                         └──────▶ rescindido
--                                └──(qualquer parte)──▶ recusado
--
-- Rascunho só a parte A enxerga (e o admin). Assinar é o que envia: ninguém
-- manda para o outro lado um contrato que ele mesmo não aceitou.
-- A troca de status acontece SÓ pelas RPCs; a RLS de UPDATE só deixa mexer em
-- rascunho, então nenhum cliente escreve 'vigente' na mão.
--
-- ─── A ASSINATURA ───────────────────────────────────────────────────────────
--
-- Lei 14.063/2020, art. 4º: simples, avançada e qualificada. Esta é a SIMPLES:
-- identifica quem assinou (sessão autenticada), grava a hora pelo relógio do
-- banco e amarra a assinatura ao arquivo por um SHA-256. O resumo é calculado
-- no navegador de quem sobe; quem assina manda o resumo que ELE conferiu, e a
-- RPC recusa se não bater com o guardado. Depois da primeira assinatura o
-- arquivo não se troca mais (a RLS só edita rascunho), então as duas
-- assinaturas valem sobre os mesmos bytes. Mudar o contrato é um ADITIVO:
-- contrato novo apontando para o de origem, assinaturas do zero.
-- Avançada e qualificada exigem certificado ICP-Brasil ou serviço pago — o
-- manifesto impresso diz isso, para o aluno não sair achando que é a mesma
-- coisa.
--
-- ─── RLS ────────────────────────────────────────────────────────────────────
--
-- Tudo escrito com `(SELECT auth_x())`, o padrão das migr. 597-599: helper
-- crua na policy roda por linha (incidente de 15/09).
--
-- IDEMPOTENTE. APLICAR NOS 4 PROJETOS.

BEGIN;

-- ────────────────────────────────────────────────────────────────────────────
-- 1. Tabelas
-- ────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.contratos (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Número humano ("CT-0007"), o que se cita na conversa e no manifesto.
  numero              bigint GENERATED BY DEFAULT AS IDENTITY,
  titulo              text NOT NULL CHECK (length(btrim(titulo)) > 0),
  objeto              text,
  parte_a             text NOT NULL CHECK (parte_a IN ('Matriz', 'SuperMax', 'MaxLook', 'TechMax')),
  parte_b             text NOT NULL CHECK (parte_b IN ('Matriz', 'SuperMax', 'MaxLook', 'TechMax')),
  valor               numeric(14,2) CHECK (valor IS NULL OR valor >= 0),
  condicoes           text,
  vigencia_inicio     date,
  vigencia_fim        date,
  arquivo_path        text NOT NULL,
  arquivo_nome        text NOT NULL,
  arquivo_mime        text,
  arquivo_tamanho     bigint,
  arquivo_sha256      text NOT NULL CHECK (arquivo_sha256 ~ '^[0-9a-f]{64}$'),
  status              text NOT NULL DEFAULT 'rascunho'
                        CHECK (status IN ('rascunho', 'aguardando', 'vigente', 'recusado', 'encerrado', 'rescindido')),
  -- Aditivo: o contrato que este altera. O original continua como estava.
  contrato_pai_id     uuid REFERENCES public.contratos(id) ON DELETE SET NULL,
  criado_por          uuid REFERENCES public.user_profiles(id) ON DELETE SET NULL,
  criado_por_nome     text,
  enviado_em          timestamptz,
  vigente_desde       timestamptz,
  encerrado_em        timestamptz,
  encerrado_por_nome  text,
  motivo_encerramento text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT contratos_partes_distintas CHECK (parte_a <> parte_b),
  CONSTRAINT contratos_vigencia_ordem CHECK (
    vigencia_inicio IS NULL OR vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio)
);

COMMENT ON TABLE public.contratos IS
  'Migr. 623 — contrato entre duas unidades. Parte A cria e assina primeiro; vigente com as duas assinaturas. Status só muda por RPC.';
COMMENT ON COLUMN public.contratos.arquivo_sha256 IS
  'Resumo SHA-256 (hex minúsculo) do arquivo, calculado no navegador de quem subiu. Toda assinatura é conferida contra ele.';

CREATE INDEX IF NOT EXISTS contratos_partes_idx ON public.contratos (parte_a, parte_b, status);
CREATE INDEX IF NOT EXISTS contratos_pai_idx    ON public.contratos (contrato_pai_id) WHERE contrato_pai_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.contratos_assinaturas (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  contrato_id     uuid NOT NULL REFERENCES public.contratos(id) ON DELETE CASCADE,
  parte           text NOT NULL CHECK (parte IN ('Matriz', 'SuperMax', 'MaxLook', 'TechMax')),
  user_id         uuid REFERENCES public.user_profiles(id) ON DELETE SET NULL,
  -- Carimbos do momento: um ano depois o manifesto continua dizendo quem era
  -- e em que cargo, mesmo que a pessoa tenha saído ou mudado de unidade.
  nome_snapshot   text NOT NULL,
  cargo_snapshot  text NOT NULL,
  arquivo_sha256  text NOT NULL,
  assinado_em     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (contrato_id, parte)
);

COMMENT ON TABLE public.contratos_assinaturas IS
  'Migr. 623 — uma assinatura por parte. Só a RPC assinar_contrato grava (sem policy de escrita).';

ALTER TABLE public.contratos             ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contratos_assinaturas ENABLE ROW LEVEL SECURITY;

